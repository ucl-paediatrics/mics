    a += data['age_2'] * data['Atrial_Fibrillation'] * -0.076182651011162505
    a += data['age_2'] * data['Corticosteroids'] * -0.12005364946742472
    a += data['age_2'] * data['Migraine'] * -0.065586917898699859
