def smoking_risk(data: pl.DataFrame) -> pl.Series:
    """Calculate the smoking risk score for each individual in the dataset."""
    # Define the risk score based on smoking status
    risk_female = {
        "Non-Smoker": 0.0000,
        "Ex Smoker": 0.13386833786546262,
        "Light Smoker": 0.56200858012438537,
        "Moderate Smoker": 0.66749593377502547,
        "Heavy Smoker": 0.84948177644830847
    }

    risk_male = {
        "Non-Smoker": 0.0000,
        "Ex Smoker": 0.19128222863388983,
        "Light Smoker": 0.55241588192645552,
        "Moderate Smoker": 0.63835053027506072,
        "Heavy Smoker": 0.78983819881858019
    }

    return pl.select(
        pl.when(
            data["Sex"] == "Male"
        ).then(
            data["Smoking Status"].replace(risk_male)
        ).otherwise(
            data["Smoking Status"].replace(risk_female)
        ).alias("smoking_risk")
    )['smoking_risk'].cast(pl.Float64)

def ethnicity_risk(data: pl.DataFrame) -> pl.Series:
    """Calculate the ethnicity risk score for each individual in the dataset."""
    risk_female = {
        "White": 0.0,
        "Indian": 0.28040314332995425,
        "Pakistani": 0.56298994142075398,
        "Bangladeshi": 0.29590000851116516,
        "Other Asian": 0.072785379877982545,
        "Black Caribbean": -0.17072135508857317,
        "Black African": -0.39371043314874971,
        "Chinese": -0.32632495283530272,
        "Other Ethnic Group": -0.17127056883241784
    }

    risk_male = {
        "White": 0.0,
        "Indian": 0.27719248760308279,
        "Pakistani": 0.47446360714931268,
        "Bangladeshi": 0.52961729919689371,
        "Other Asian": 0.035100159186299017,
        "Black Caribbean": -0.35807899669327919,
        "Black African": -0.40056485232165140,
        "Chinese": -0.41522792889830173,
        "Other Ethnic Group": -0.26321348134749967
    }

    # Check for invalid entries in the Ethnicity column
    assert set(risk_female.keys()) == set(risk_male.keys()), \
    "Risk dictionaries for males and females do not have the same keys"
    valid_keys = set(risk_female.keys())
    if any(data["Ethnicity"].is_in(valid_keys).not_()):
        raise ValueError("Invalid entries found in the Ethnicity column")


    return pl.select(
        pl.when(
            data["Sex"] == "Male"
        ).then(
            data["Ethnicity"].replace(risk_male)
        ).otherwise(
            data["Ethnicity"].replace(risk_female)
        ).alias("ethnicity_risk")
    )['ethnicity_risk'].cast(pl.Float64)
