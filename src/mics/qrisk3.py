    a += data['age_1'] * (data['Smoking Status'] == "Light Smoker") * -2.7430383403573337
    a += data['age_1'] * (data['Smoking Status'] == "Moderate Smoker") * -0.86608088829392182
    a += data['age_1'] * (data['Smoking Status'] == "Heavy Smoker") * 0.90241562369710648
    a += data['age_1'] * data['Atrial_Fibrillation'] * 19.938034889546561
    a += data['age_1'] * data['Corticosteroids'] * -0.98408045235936281
    a += data['age_1'] * data['Migraine'] * 1.7634979587872999
    a += data['age_1'] * data['CKD'] * -3.5874047731694114
    a += data['age_1'] * data['SLE'] * 19.690303738638292
    a += data['age_1'] * data['Treated Hypertension'] * 11.872809733921812
    a += data['age_1'] * data['Type 1 Diabetes'] * -1.2444332714320747
    a += data['age_1'] * data['Type 2 Diabetes'] * 6.8652342000009599
    a += data['age_1'] * data['bmi_1'] * 23.802623412141742
    a += data['age_1'] * data['bmi_2'] * -71.184947692087007
    a += data['age_1'] * data['Family History of CVD'] * 0.99467807940435127
    a += data['age_1'] * data['Systolic_Blood_Pressure'] * 0.034131842338615485
    a += data['age_1'] * data['Townsend_Score'] * -1.0301180802035639
    a += data['age_2'] * (data['Smoking Status'] == "Ex Smoker") * -0.075589244643193026
