import numpy as np
import polars as pl


def calculate_qrisk3(data: pl.DataFrame) -> pl.Series:
    """Calculate the QRISK3 score for each individual in the dataset.
    
    This function returns the 10 year risk of cardiovascular disease for each individual in the dataset, 
    as a percentage.

    TODO: Implement statin effect. 
    """
    # Apply age and BMI transformations
    data = data.with_row_index()
    # Split the data in to male and female; apply the appropriate risk calculation to each group,
    # and then combine the results back together in the original order
    male_data = data.filter(pl.col("Sex") == "Male")
    female_data = data.filter(pl.col("Sex") == "Female")

    male_risk_scores = male_data.with_columns(male_risk(male_data))
    female_risk_scores = female_data.with_columns(female_risk(female_data))

    # Combine the results back together in the original order using the row index
    risk_scores = pl.concat([male_risk_scores, female_risk_scores]).sort("index")["risk"]

    return risk_scores

def female_age_bmi_transformation(data: pl.DataFrame) -> pl.DataFrame:
    """Apply the age and BMI transformations to the dataset."""
    return data.with_columns(
        (pl.col("Age") / 10).alias("dage"),
        (pl.col("BMI") / 10).alias("dbmi")
    ).with_columns(
        pl.col("dage").pow(-2).alias("age_1"),
        pl.col("dage").alias("age_2"),
        pl.col("dbmi").pow(-2).alias("bmi_1"),
        (pl.col("dbmi").pow(-2) * pl.col("dbmi").log()).alias("bmi_2")
    )

def male_age_bmi_transformation(data: pl.DataFrame) -> pl.DataFrame:
    """Apply the age and BMI transformations to the dataset."""
    return data.with_columns(
        (pl.col("Age") / 10).alias("dage"),
        (pl.col("BMI") / 10).alias("dbmi")
    ).with_columns(
        pl.col("dage").pow(-1).alias("age_1"),
        pl.col("dage").pow(3).alias("age_2"),
        pl.col("dbmi").pow(-2).alias("bmi_1"),
        (pl.col("dbmi").pow(-2) * pl.col("dbmi").log()).alias("bmi_2")
    )

